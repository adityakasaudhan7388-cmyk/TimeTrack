@app.route("/api/tasks", methods=["GET", "POST"])
def tasks():
    with get_database() as connection:

        if request.method == "GET":
            rows = connection.execute("""
                SELECT id, task_text, completed
                FROM tasks
                ORDER BY id DESC
            """).fetchall()

            return jsonify([dict(row) for row in rows])

        data = request.get_json(silent=True) or {}

        # Accept both frontend field names
        task_text = str(
            data.get("task_text") or data.get("task") or ""
        ).strip()

        if not task_text:
            return jsonify({
                "error": "Task cannot be empty"
            }), 400

        row = connection.execute("""
            INSERT INTO tasks (task_text, completed)
            VALUES (%s, 0)
            RETURNING id, task_text, completed
        """, (task_text,)).fetchone()

        return jsonify(dict(row))


@app.route("/api/tasks/<int:task_id>", methods=["PATCH", "DELETE"])
def update_task(task_id):
    with get_database() as connection:

        if request.method == "PATCH":
            data = request.get_json(silent=True) or {}
            completed = 1 if data.get("completed") else 0

            connection.execute("""
                UPDATE tasks
                SET completed = %s
                WHERE id = %s
            """, (completed, task_id))

            return jsonify({"success": True})

        connection.execute("""
            DELETE FROM tasks
            WHERE id = %s
        """, (task_id,))

        return jsonify({"success": True})


