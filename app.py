@app.route("/api/weekly-time", methods=["GET"])
def weekly_time():
    today = date.today()
    monday = today - timedelta(days=today.weekday())

    days = []

    with get_database() as connection:

        for i in range(7):
            current_day = monday + timedelta(days=i)
            day_string = current_day.isoformat()

            actual = get_daily_actual(connection, day_string)

            plan_row = connection.execute("""
                SELECT planned_seconds
                FROM daily_plans
                WHERE plan_date = %s
            """, (day_string,)).fetchone()

            planned = (
                int(plan_row["planned_seconds"])
                if plan_row else 0
            )

            days.append({
                "date": day_string,
                "label": current_day.strftime("%a"),
                "study_seconds": actual,
                "planned_seconds": planned
            })

    return jsonify({"days": days})


