@app.route("/api/daily-time", methods=["GET"])
def daily_time():
    today = get_today()

    with get_database() as connection:

        plan_row = connection.execute("""
            SELECT planned_seconds
            FROM daily_plans
            WHERE plan_date = %s
        """, (today,)).fetchone()

        planned = (
            int(plan_row["planned_seconds"])
            if plan_row else 0
        )

        actual = get_daily_actual(connection, today)

        sessions = connection.execute("""
            SELECT start_time, end_time, duration_seconds
            FROM time_sessions
            WHERE session_date = %s
            ORDER BY id DESC
        """, (today,)).fetchall()

        return jsonify({
            "planned_seconds": planned,
            "actual_seconds": actual,
            "remaining_seconds": max(0, planned - actual),
            "sessions": [dict(row) for row in sessions]
        })


