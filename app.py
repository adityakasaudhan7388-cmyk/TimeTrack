@app.route("/api/sessions/start", methods=["POST"])
def start_session():
    now = datetime.now()
    today = now.date().isoformat()
    start_time = now.isoformat(timespec="seconds")

    with get_database() as connection:

        existing = connection.execute("""
            SELECT id
            FROM time_sessions
            WHERE end_time IS NULL
            ORDER BY id DESC
            LIMIT 1
        """).fetchone()

        if existing:
            return jsonify({
                "success": True,
                "message": "A session is already running"
            })

        connection.execute("""
            INSERT INTO time_sessions (
                session_date,
                start_time,
                end_time,
                duration_seconds
            )
            VALUES (%s, %s, NULL, 0)
        """, (today, start_time))

        return jsonify({"success": True})


# =====================================
# STOP STUDY SESSION
# =====================================

@app.route("/api/sessions/stop", methods=["POST"])
def stop_session():
    now = datetime.now()

    with get_database() as connection:

        session = connection.execute("""
            SELECT id, start_time, session_date
            FROM time_sessions
            WHERE end_time IS NULL
            ORDER BY id DESC
            LIMIT 1
        """).fetchone()

        if not session:
            return jsonify({
                "success": False,
                "message": "No active session found"
            }), 400

        start_time = datetime.fromisoformat(session["start_time"])
        duration = max(
            0, int((now - start_time).total_seconds())
        )

        today = get_today()

        previous_actual = get_daily_actual(
            connection, session["session_date"]
        )

        connection.execute("""
            UPDATE time_sessions
            SET end_time = %s,
                duration_seconds = %s
            WHERE id = %s
        """, (
            now.isoformat(timespec="seconds"),
            duration,
            session["id"]
        ))

        if session["session_date"] == today:
            plan_row = connection.execute("""
                SELECT planned_seconds
                FROM daily_plans
                WHERE plan_date = %s
            """, (today,)).fetchone()

            planned = (
                int(plan_row["planned_seconds"])
                if plan_row else 0
            )

            actual = get_daily_actual(connection, today)

            previous_extra = max(0, previous_actual - planned)
            current_extra = max(0, actual - planned)
            newly_earned_extra = current_extra - previous_extra

            apply_extra_study(connection, newly_earned_extra)

        update_backlog(connection)

        return jsonify({
            "success": True,
            "duration_seconds": duration
        })


