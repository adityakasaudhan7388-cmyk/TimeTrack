
import os
from datetime import date, datetime, timedelta

import psycopg
from psycopg.rows import dict_row
from flask import Flask, render_template, request, jsonify

app = Flask(__name__)

MAX_BACKLOG_SECONDS = 7 * 60 * 60
BACKLOG_DAYS = 30


# =====================================
# DATABASE CONNECTION
# =====================================

def get_database():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is missing. Add your PostgreSQL connection URL "
            "to the environment variables."
        )

    if database_url.startswith("postgres://"):
        database_url = database_url.replace(
            "postgres://", "postgresql://", 1
        )

    return psycopg.connect(
        database_url,
        row_factory=dict_row,
        connect_timeout=15,
        autocommit=True
    )


# =====================================
# DATABASE SETUP
# =====================================

def create_database():
    with get_database() as connection:

        connection.execute("""
            CREATE TABLE IF NOT EXISTS tasks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                task_text TEXT NOT NULL,
                completed INTEGER DEFAULT 0
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS timer (
                id INTEGER PRIMARY KEY,
                total_seconds BIGINT DEFAULT 0
            )
        """)

        connection.execute("""
            INSERT INTO timer (id, total_seconds)
            VALUES (1, 0)
            ON CONFLICT (id) DO NOTHING
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS daily_plans (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                plan_date TEXT UNIQUE NOT NULL,
                planned_seconds BIGINT DEFAULT 0
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS time_sessions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_date TEXT NOT NULL,
                start_time TEXT NOT NULL,
                end_time TEXT,
                duration_seconds BIGINT DEFAULT 0
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS backlog (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                plan_date TEXT UNIQUE NOT NULL,
                original_seconds BIGINT DEFAULT 0,
                remaining_seconds BIGINT DEFAULT 0,
                deadline TEXT NOT NULL,
                status TEXT DEFAULT 'active'
            )
        """)


# =====================================
# COMMON FUNCTIONS
# =====================================

def get_today():
    return date.today().isoformat()


def get_daily_actual(connection, day):
    result = connection.execute("""
        SELECT COALESCE(SUM(duration_seconds), 0) AS total
        FROM time_sessions
        WHERE session_date = %s
    """, (day,)).fetchone()

    return int(result["total"] or 0)


# =====================================
# BACKLOG SYSTEM
# =====================================

def update_backlog(connection):
    today = get_today()

    plans = connection.execute("""
        SELECT plan_date, planned_seconds
        FROM daily_plans
        WHERE plan_date < %s
        ORDER BY plan_date ASC
    """, (today,)).fetchall()

    for plan in plans:
        planned = int(plan["planned_seconds"] or 0)
        actual = get_daily_actual(connection, plan["plan_date"])
        remaining = max(0, planned - actual)

        if remaining <= 0:
            continue

        deadline = (
            date.fromisoformat(plan["plan_date"])
            + timedelta(days=BACKLOG_DAYS)
        ).isoformat()

        connection.execute("""
            INSERT INTO backlog (
                plan_date,
                original_seconds,
                remaining_seconds,
                deadline,
                status
            )
            VALUES (%s, %s, %s, %s, 'active')
            ON CONFLICT (plan_date) DO NOTHING
        """, (
            plan["plan_date"],
            remaining,
            remaining,
            deadline
        ))

    active_items = connection.execute("""
        SELECT id, remaining_seconds
        FROM backlog
        WHERE status = 'active'
        ORDER BY plan_date ASC
    """).fetchall()

    total_backlog = sum(
        int(item["remaining_seconds"] or 0)
        for item in active_items
    )

    if total_backlog > MAX_BACKLOG_SECONDS:
        excess = total_backlog - MAX_BACKLOG_SECONDS

        for item in active_items:
            if excess <= 0:
                break

            remaining = int(item["remaining_seconds"] or 0)
            reduction = min(remaining, excess)
            new_remaining = remaining - reduction
            excess -= reduction

            connection.execute("""
                UPDATE backlog
                SET remaining_seconds = %s,
                    status = %s
                WHERE id = %s
            """, (
                new_remaining,
                "completed" if new_remaining == 0 else "active",
                item["id"]
            ))

    connection.execute("""
        UPDATE backlog
        SET status = 'expired'
        WHERE status = 'active'
        AND deadline < %s
    """, (today,))


def apply_extra_study(connection, extra_seconds):
    extra_seconds = max(0, int(extra_seconds or 0))

    if extra_seconds <= 0:
        return

    items = connection.execute("""
        SELECT id, remaining_seconds
        FROM backlog
        WHERE status = 'active'
        ORDER BY plan_date ASC
    """).fetchall()

    for item in items:
        if extra_seconds <= 0:
            break

        remaining = int(item["remaining_seconds"] or 0)
        reduction = min(remaining, extra_seconds)
        new_remaining = remaining - reduction
        extra_seconds -= reduction

        connection.execute("""
            UPDATE backlog
            SET remaining_seconds = %s,
                status = %s
            WHERE id = %s
        """, (
            new_remaining,
            "completed" if new_remaining == 0 else "active",
            item["id"]
        ))


