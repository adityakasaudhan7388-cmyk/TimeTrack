@app.route("/api/plan", methods=["GET", "POST"])
def plan():
    today = get_today()

    with get_database() as connection:

        if request.method == "GET":
            row = connection.execute("""
                SELECT planned_seconds
                FROM daily_plans
                WHERE plan_date = %s
            """, (today,)).fetchone()

            return jsonify({
                "planned_seconds": (
                    int(row["planned_seconds"]) if row else 0
                )
            })

        data = request.get_json(silent=True) or {}

        try:
            planned_hours = float(data.get("planned_hours", 0))
        except (TypeError, ValueError):
            return jsonify({
                "error": "Invalid planned hours"
            }), 400

        if not 0 <= planned_hours <= 24:
            return jsonify({
                "error": "Hours must be between 0 and 24"
            }), 400

        planned_seconds = int(planned_hours * 3600)

        connection.execute("""
            INSERT INTO daily_plans (plan_date, planned_seconds)
            VALUES (%s, %s)
            ON CONFLICT (plan_date)
            DO UPDATE SET planned_seconds = EXCLUDED.planned_seconds
        """, (today, planned_seconds))

        update_backlog(connection)

        return jsonify({
            "success": True,
            "planned_seconds": planned_seconds
        })


